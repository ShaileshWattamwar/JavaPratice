public class Operator2 {
    public static void main(String[] args) {


        int A = 200;
        int B = 100;
        int C = 200;

        int sum = A + B + C;
        int Subtract = A-C;
        int Multiply = A * B * C;


        System.out.println(sum);
        System.out.println(Subtract);
        System.out.println(Multiply);
        System.out.println(A<B);
        System.out.println(A>B);
        System.out.println(A==C);
    }

}
