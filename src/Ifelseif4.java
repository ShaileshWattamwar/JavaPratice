public class Ifelseif4 {
    public static void main(String[] args) {
        int month = 3;

        if (month == 1) {
            System.out.println("days are 31");
        } else if (month == 2) {
            System.out.println("days are 28 or 29");
        } else if (month == 3) {
            System.out.println("days are 30");
        } else if (month == 4) {
            System.out.println("days are 30");
        } else {
            System.out.println("days are 31");
        }
    }
}

