public class Ifelseif3 {
    public static void main(String[] args) {
        int salary=10000;

        if(salary>100000){
            System.out.println("salary is less");
        } else if (salary>200000){
            System.out.println("salary is less");
        }else if(salary>300000){
            System.out.println("salary is less");
        }else{
            System.out.println("salary is very low");

        }
    }
}
